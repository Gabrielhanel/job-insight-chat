def _compilar(dic: dict[str, list[str]]) -> dict[str, re.Pattern]:
    out = {}
    for nome, variantes in dic.items():
        alt = "|".join(re.escape(v) for v in sorted(variantes, key=len, reverse=True))
        # evita casar dentro de outras palavras (ex.: "java" em "javascript")
        out[nome] = re.compile(rf"(?<![\w.+#]){'(?:' + alt + ')'}(?![\w+#])", re.IGNORECASE)
    return out


