_SOFT = _compilar(SOFT)

_NIVEIS = [
    ("estagio", r"est[áa]gi|\bintern\b|trainee"),
    ("lead", r"\blead\b|\bl[íi]der\b|tech lead"),
    ("senior", r"s[êe]nior|\bsr\b"),
    ("pleno", r"\bpleno\b|\bpl\b|\bmid\b"),
    ("junior", r"j[úu]nior|\bjr\b"),
]


def _nivel(titulo: str, texto: str) -> str:
    for alvo in (titulo, texto):
        for nome, padrao in _NIVEIS:
            if re.search(padrao, alvo, re.IGNORECASE):
                return nome
    return "nao_informado"


def _anos(texto: str) -> int | None:
    m = re.search(r"(\d{1,2})\s*\+?\s*(?:anos|years?)\s+(?:de\s+|of\s+)?experi", texto, re.I) or re.search(
        r"experi[eê]ncia[^.\n]{0,40}?(\d{1,2})\s*\+?\s*(?:anos|years?)", texto, re.I
    )
    return int(m.group(1)) if m else None


# negação curta antes do termo ("não é necessário conhecer X", "sem experiência em X")
_NEG = re.compile(r"n[ãa]o\s+(?:\w+\s+){0,2}?(?:necess|obrigat|preciso|exig)|\bsem\b|dispens", re.I)
# a partir de um título de seção como "Diferenciais" ou "Desejável", tudo é opcional
_SECAO = re.compile(r"^\W*(diferenciais?|desej[áa]ve(?:l|is)|nice to have|b[ôo]nus|plus)\b", re.I | re.M)


def _achou(padrao: re.Pattern, texto: str) -> bool:
    return any(
        not _NEG.search(texto[max(0, m.start() - 40) : m.start()]) for m in padrao.finditer(texto)
    )


def extrair_dicionario(vaga: dict) -> dict:
    titulo, desc = vaga["titulo"], vaga["descricao"]
    texto = f"{titulo}\n{desc}"
    m = _SECAO.search(desc)
    obrig, desej = (desc[: m.start()], desc[m.start() :]) if m else (desc, "")
    obrig = f"{titulo}\n{obrig}"
    tec = [n for n, p in _TEC.items() if _achou(p, obrig)]
    return {
        "tecnologias": tec,
        "diferenciais": [n for n, p in _TEC.items() if n not in tec and _achou(p, desej)],
        "soft_skills": [n for n, p in _SOFT.items() if _achou(p, texto)],
        "nivel": _nivel(titulo, texto),
        "anos_experiencia_min": _anos(texto),
    }